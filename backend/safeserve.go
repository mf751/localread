package main

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
)

// ErrUnsafePath is returned when a user-supplied path attempts to escape the
// data root (directory traversal), is absolute, or contains a NUL byte.
var ErrUnsafePath = errors.New("unsafe path")

// safeJoin resolves rel against root and guarantees the result stays inside
// root. It is the single choke point for every user-supplied path that reaches
// the filesystem, so that library names, upload names and cache keys can never
// read or write outside the data directory.
//
// It rejects:
//   - empty / whitespace-only names
//   - absolute paths (unix and Windows style, including drive letters)
//   - NUL bytes
//   - any result that, after cleaning, is not strictly below root
//
// The containment check is done on the fully cleaned, absolute form of both
// paths rather than by string-prefixing, which avoids the classic
// "/data" matching "/data-secret" bug.
func safeJoin(root, rel string) (string, error) {
	if strings.TrimSpace(rel) == "" {
		return "", ErrUnsafePath
	}
	if strings.ContainsRune(rel, 0) {
		return "", ErrUnsafePath
	}
	if filepath.IsAbs(rel) || strings.HasPrefix(rel, "/") || strings.HasPrefix(rel, `\`) {
		return "", ErrUnsafePath
	}
	// Windows-style drive letters (C:\...) are absolute even on other OSes.
	if len(rel) >= 2 && rel[1] == ':' {
		return "", ErrUnsafePath
	}

	absRoot, err := filepath.Abs(root)
	if err != nil {
		return "", err
	}
	joined := filepath.Join(absRoot, rel)
	absJoined, err := filepath.Abs(joined)
	if err != nil {
		return "", err
	}

	// Reject the root itself and anything outside it.
	within, err := isWithin(absRoot, absJoined)
	if err != nil {
		return "", err
	}
	if !within {
		return "", ErrUnsafePath
	}
	return absJoined, nil
}

// isWithin reports whether target is strictly inside root (not equal to it).
func isWithin(root, target string) (bool, error) {
	rel, err := filepath.Rel(root, target)
	if err != nil {
		return false, ErrUnsafePath
	}
	if rel == "." {
		return false, nil
	}
	if rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return false, nil
	}
	return true, nil
}

// safeID validates opaque identifiers (novel/chapter ids) used to build
// cache sub-paths. Ids are generated by the app, but validating on the way in
// keeps a malformed id from ever reaching safeJoin with surprising content.
func safeID(id string) bool {
	if id == "" || len(id) > 64 {
		return false
	}
	for _, r := range id {
		switch {
		case r >= 'a' && r <= 'z':
		case r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9':
		case r == '-' || r == '_':
		default:
			return false
		}
	}
	return true
}

// ensureDir creates dir (and parents) restricted to owner traversal only.
func ensureDir(dir string) error {
	return os.MkdirAll(dir, 0o700)
}
