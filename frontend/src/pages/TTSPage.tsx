import { useEffect, useState } from "react";
import { api } from "../api";
import type { TTSProvider, TTSProviderInput } from "../types";

const emptyForm: TTSProviderInput = {
  name: "",
  baseUrl: "",
  apiKey: "",
  model: "",
  voice: "",
  speed: 1,
  lang: "",
};

function timingBadge(p: TTSProvider) {
  switch (p.timings) {
    case "yes":
      return <span className="badge ok">word timings</span>;
    case "no":
      return <span className="badge">audio only</span>;
    default:
      return <span className="badge warn">timings unknown</span>;
  }
}

export default function TTSPage() {
  const [providers, setProviders] = useState<TTSProvider[]>([]);
  const [form, setForm] = useState<TTSProviderInput>(emptyForm);
  const [editId, setEditId] = useState<number | null>(null);
  const [showForm, setShowForm] = useState(false);
  const [busy, setBusy] = useState<number | "new" | null>(null);
  const [error, setError] = useState("");
  const [message, setMessage] = useState("");

  const load = () =>
    api
      .listTTSProviders()
      .then((d) => setProviders(d.providers))
      .catch((e) => setError(e instanceof Error ? e.message : "failed to load"));

  useEffect(() => {
    load();
  }, []);

  const set = <K extends keyof TTSProviderInput>(
    key: K,
    value: TTSProviderInput[K],
  ) => setForm((f) => ({ ...f, [key]: value }));

  const startNew = () => {
    setForm(emptyForm);
    setEditId(null);
    setShowForm(true);
    setError("");
    setMessage("");
  };

  const startEdit = (p: TTSProvider) => {
    setForm({
      name: p.name,
      baseUrl: p.baseUrl,
      apiKey: "",
      model: p.model,
      voice: p.voice,
      speed: p.speed,
      lang: p.lang,
    });
    setEditId(p.id);
    setShowForm(true);
    setError("");
    setMessage("");
  };

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError("");
    setMessage("");
    setBusy(editId ?? "new");
    try {
      const verb = editId != null ? "Updated" : "Added";
      const r =
        editId != null
          ? await api.updateTTSProvider(editId, form)
          : await api.createTTSProvider(form);
      setMessage(
        r.reachable
          ? `${verb} “${r.provider.name}”.`
          : `${verb} “${r.provider.name}”, but it did not respond${
              r.detail ? `: ${r.detail}` : "."
            }`,
      );
      setShowForm(false);
      setEditId(null);
      setForm(emptyForm);
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : "save failed");
    } finally {
      setBusy(null);
    }
  };

  const activate = async (p: TTSProvider) => {
    setError("");
    setMessage("");
    try {
      await api.activateTTSProvider(p.id);
      setMessage(`Now using “${p.name}”.`);
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : "failed to switch");
    }
  };

  const test = async (p: TTSProvider) => {
    setError("");
    setMessage("");
    setBusy(p.id);
    try {
      const r = await api.testTTSProvider(p.id);
      setMessage(
        r.reachable
          ? `“${p.name}” is online — ${
              r.timings ? "returns word timings" : "audio only"
            }.`
          : `“${p.name}” did not respond${r.detail ? `: ${r.detail}` : "."}`,
      );
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : "test failed");
    } finally {
      setBusy(null);
    }
  };

  const remove = async (p: TTSProvider) => {
    if (!confirm(`Delete “${p.name}”? Cached audio for it stays on disk.`)) return;
    setError("");
    setMessage("");
    try {
      await api.deleteTTSProvider(p.id);
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : "delete failed");
    }
  };

  return (
    <div className="page">
      <div className="page-head">
        <h1>TTS models</h1>
        <button className="primary" onClick={startNew}>
          New model
        </button>
      </div>

      <p className="muted small">
        Speech is generated by the model you choose below. Models that return
        word timings get word-by-word highlighting in the reader; models that
        only return audio just play.
      </p>

      {error && <p className="error">{error}</p>}
      {message && <p className="ok small">{message}</p>}

      {showForm && (
        <form className="card stack" onSubmit={submit}>
          <h2>{editId != null ? "Edit model" : "New model"}</h2>
          <div className="row">
            <label className="grow">
              Name
              <input
                value={form.name}
                onChange={(e) => set("name", e.target.value)}
                placeholder="Kokoro (local)"
                required
              />
            </label>
            <label className="grow">
              Base URL
              <input
                value={form.baseUrl}
                onChange={(e) => set("baseUrl", e.target.value)}
                placeholder="http://localhost:8880"
                required
              />
            </label>
          </div>
          <label>
            API key {editId != null && <span className="muted tiny">(leave blank to keep current)</span>}
            <input
              type="password"
              value={form.apiKey}
              onChange={(e) => set("apiKey", e.target.value)}
              placeholder="optional"
              autoComplete="off"
            />
          </label>
          <div className="row">
            <label className="grow">
              Model
              <input
                value={form.model}
                onChange={(e) => set("model", e.target.value)}
                placeholder="kokoro"
              />
            </label>
            <label className="grow">
              Voice
              <input
                value={form.voice}
                onChange={(e) => set("voice", e.target.value)}
                placeholder="af_heart"
              />
            </label>
          </div>
          <div className="row">
            <label className="grow">
              Speed
              <input
                type="number"
                min={0.25}
                max={4}
                step={0.05}
                value={form.speed}
                onChange={(e) => set("speed", Number(e.target.value))}
              />
            </label>
            <label className="grow">
              Language
              <input
                value={form.lang}
                onChange={(e) => set("lang", e.target.value)}
                placeholder="a"
              />
            </label>
          </div>
          <div className="row">
            <button className="primary" type="submit" disabled={busy !== null}>
              {busy !== null ? "saving…" : editId != null ? "Save changes" : "Add model"}
            </button>
            <button
              type="button"
              className="ghost"
              onClick={() => {
                setShowForm(false);
                setEditId(null);
              }}
            >
              Cancel
            </button>
          </div>
          <p className="muted tiny">
            Base URL is the server root only (e.g.{" "}
            <code>http://localhost:8080</code> or{" "}
            <code>http://localhost:8880</code>) — not the full endpoint. The
            backend probes the model when it is saved: Kokoro’s{" "}
            <code>/dev/captioned_speech</code> endpoint gives timings, while a
            plain OpenAI-style <code>/v1/audio/speech</code> endpoint gives audio
            only. LocalAI’s <code>qwen3-tts-cpp</code> needs a voice profile such
            as <code>localai://voice-profiles/&lt;id&gt;</code>, not a generic
            name like <code>default</code>.
          </p>
        </form>
      )}

      <div className="stack" style={{ marginTop: "1rem" }}>
        {providers.length === 0 && (
          <p className="empty">No models yet. Add one to generate speech.</p>
        )}
        {providers.map((p) => (
          <div key={p.id} className="card">
            <div className="row between">
              <div className="stack" style={{ gap: "0.3rem" }}>
                <div className="row">
                  <strong>{p.name}</strong>
                  {p.active && <span className="badge ok">in use</span>}
                  {timingBadge(p)}
                  {p.hasKey && <span className="badge">key set</span>}
                </div>
                <div className="muted small">
                  <code>{p.baseUrl}</code>
                  {p.model && <> · <code>{p.model}</code></>}
                  {p.voice && <> · <code>{p.voice}</code></>}
                  {p.speed !== 1 && <> · ×{p.speed}</>}
                  {p.lang && <> · lang {p.lang}</>}
                </div>
              </div>
              <div className="row">
                {!p.active && (
                  <button
                    className="ghost small"
                    onClick={() => activate(p)}
                    disabled={busy !== null}
                  >
                    Use
                  </button>
                )}
                <button
                  className="ghost small"
                  onClick={() => test(p)}
                  disabled={busy !== null}
                >
                  {busy === p.id ? "testing…" : "Test"}
                </button>
                <button
                  className="ghost small"
                  onClick={() => startEdit(p)}
                  disabled={busy !== null}
                >
                  Edit
                </button>
                <button
                  className="danger small"
                  onClick={() => remove(p)}
                  disabled={busy !== null}
                >
                  Delete
                </button>
              </div>
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}
